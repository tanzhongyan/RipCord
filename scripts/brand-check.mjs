#!/usr/bin/env node
// Brand gate: fails on scaffold defaults, missing brand files and broken
// site-config wiring.

import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const failures = [];

const walk = (dir, out = []) => {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
};

const scanFiles = ["src", "public"]
  .map((d) => join(root, d))
  .flatMap((d) => {
    try {
      return walk(d);
    } catch {
      return [];
    }
  });

// 1. Forbidden scaffold defaults. Tests assert the absence, so they are exempt.
const forbidden = ["Create T3 App", "Generated by create-t3-app", "create.t3.gg"];
for (const file of scanFiles.filter((f) => !/(\.test\.|\.spec\.)/.test(f))) {
  let text;
  try {
    text = readFileSync(file, "utf8");
  } catch {
    continue;
  }
  if (text.includes("\0")) continue;
  for (const phrase of forbidden) {
    if (text.includes(phrase)) failures.push(`brand-check: ${file} still contains "${phrase}"`);
  }
}

// 2. Brand files exist.
for (const rel of [
  "src/app/icon.svg",
  "src/app/apple-icon.tsx",
  "src/app/opengraph-image.tsx",
  "public/mark.svg",
]) {
  try {
    statSync(join(root, rel));
  } catch {
    failures.push(`brand-check: missing ${rel}`);
  }
}
try {
  statSync(join(root, "public/favicon.ico"));
  failures.push("brand-check: public/favicon.ico is the scaffold icon; icon.svg replaces it");
} catch {}

// 3. Wiring: the layout and the share images read the site config.
const read = (rel) => {
  try {
    return readFileSync(join(root, rel), "utf8");
  } catch {
    return "";
  }
};
const layout = read("src/app/layout.tsx");
if (!layout.includes("site.") || !layout.includes("shared/config/site")) {
  failures.push("brand-check: src/app/layout.tsx does not read the site config");
}
if (/title:\s*"[^"]*"/.test(layout)) {
  failures.push("brand-check: src/app/layout.tsx hard-codes a title; use site.defaultTitle");
}
for (const rel of ["src/app/apple-icon.tsx", "src/app/opengraph-image.tsx"]) {
  if (!read(rel).includes("site."))
    failures.push(`brand-check: ${rel} does not read the site config`);
}

// 4. The site config carries the product name.
const siteText = read("src/shared/config/site.ts");
if (!/name:\s*"RipCord"/.test(siteText)) {
  failures.push('brand-check: site.name must be "RipCord"');
}
if (!siteText.includes("%s · RipCord")) {
  failures.push('brand-check: site.titleTemplate must be "%s · RipCord"');
}

if (failures.length > 0) {
  for (const failure of failures) console.error(failure);
  process.exit(1);
}
console.log("brand-check: ok");
